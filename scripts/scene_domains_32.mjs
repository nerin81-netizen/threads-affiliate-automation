/**
 * 32대 도메인 중 본문 텍스트와 가장 부합하는 최적의 프리셋을 스코어링 기반으로 도출한다.
 * @param {string} text 본문 텍스트
 * @returns {object} { setting, light, camera, domainKey }
 */
export function matchDomainScene(text = '') {
  const t = text.toLowerCase();
  let bestKey = 'dev_coding';
  let maxScore = 0;

  // 32개 도메인을 순회하며 매칭 점수 계산
  for (const [key, def] of Object.entries(DOMAIN_CATEGORIES_32)) {
    const matches = t.match(new RegExp(def.keywords.source, 'gi'));
    const score = matches ? matches.length : 0;
    if (score > maxScore) {
      maxScore = score;
      bestKey = key;
    }
  }

  // 매칭된 키워드가 전혀 없을 경우의 스마트 폴백: 일상/힐링 또는 비즈니스
  if (maxScore === 0) {
    if (/이야기|하루|생각|마음|오늘|시간/.test(t)) {
      bestKey = 'night_healing';
    } else {
      bestKey = 'dev_coding';
    }
  }

  const domain = DOMAIN_CATEGORIES_32[bestKey];
  const presets = domain.presets;
  const picked = presets[Math.floor(Math.random() * presets.length)];

  return {
    ...picked,
    domainKey: bestKey
  };
}
