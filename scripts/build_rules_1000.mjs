function expandTo100(baseThemes, categoryName, startId) {
  const variations = [
    (name, rule) => ({ name: `${name}`, rule: `${rule}` }),
    (name, rule) => ({ name: `[실속/생활] ${name}`, rule: `실속 있는 일상의 생생함이 돋보이도록, ${rule}` }),
    (name, rule) => ({ name: `[야외/모빌리티] ${name}`, rule: `탁 트인 야외 도로와 이동의 현장감을 살려, ${rule}` }),
    (name, rule) => ({ name: `[도심/프로] ${name}`, rule: `현대적인 도시 감성과 지적인 세련미를 더하여, ${rule}` }),
    (name, rule) => ({ name: `[감성/힐링] ${name}`, rule: `차분하고 낭만적인 삶의 온기를 가득 담아, ${rule}` })
  ];

  const result = [];
  let id = startId;
  for (let v = 0; v < variations.length; v++) {
    for (let i = 0; i < baseThemes.length; i++) {
      const [n, r] = baseThemes[i];
      const item = variations[v](n, r);
      result.push({ id: id++, name: item.name, rule: item.rule });
    }
  }
  return result;
}

