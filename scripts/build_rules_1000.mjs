/**
 * 테마 친화 키워드가 포함된 항목을 우선 선별하고, 없으면 전체 배열에서 랜덤 추출한다.
 */
function pickHarmonyItem(items, affinityKeywords = []) {
  if (!affinityKeywords || affinityKeywords.length === 0) {
    return items[Math.floor(Math.random() * items.length)];
  }
  const matched = items.filter(item => 
    affinityKeywords.some(kw => (item.name && item.name.includes(kw)) || (item.rule && item.rule.includes(kw)))
  );
  if (matched.length > 0) {
    return matched[Math.floor(Math.random() * matched.length)];
  }
  return items[Math.floor(Math.random() * items.length)];
}

